"""Summarize residual TRAIN misses by reference type, intent, and abstention cause.

This tool is diagnostic only: it never modifies inference policy or uses public
test labels. Run after scripts/run.py --dump and --logs on TRAIN.
"""
from __future__ import annotations

import argparse
import json
import os
from collections import Counter, defaultdict

import sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from datamate.scorer import score_one  # noqa: E402


def load_jsonl(path):
    with open(path, encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def reason(pred, dump_row, trace):
    if pred.get("type") != "abstain":
        return "answered_incorrectly"
    raw = (dump_row or {}).get("pred") or {}
    feats = (dump_row or {}).get("feats") or {}
    if raw.get("type") not in (None, "abstain"):
        return "decision_filtered_candidate"
    if trace.get("template_error"):
        return "template_exception"
    candidates = trace.get("candidates") or []
    if any(c.get("family") == "rule" for c in candidates):
        return "only_rule_or_no_candidate"
    if not candidates:
        if trace.get("spec", {}).get("intent") is None:
            return "intent_unrecognized"
        return "no_template_for_detected_intent"
    if all(c.get("key") in (None, "None") for c in candidates):
        return "invalid_candidates"
    return "unsupported_or_conflicting_candidates"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", required=True, help="TRAIN split with questions.jsonl and answers.jsonl")
    ap.add_argument("--submission", required=True, help="Saved TRAIN submission.jsonl")
    ap.add_argument("--dump", required=True, help="Saved TRAIN run.py --dump file")
    ap.add_argument("--logs", help="Per-question JSON log directory")
    ap.add_argument("--out", help="Write summary JSON")
    ap.add_argument("--show", type=int, default=25)
    args = ap.parse_args()

    questions = {r["id"]: r for r in load_jsonl(os.path.join(args.split, "questions.jsonl"))}
    golds = {r["id"]: r for r in load_jsonl(os.path.join(args.split, "answers.jsonl"))}
    preds = {r["id"]: r for r in load_jsonl(args.submission)}
    dumps = {r["id"]: r for r in load_jsonl(args.dump)}
    by_type, by_intent, by_cause = Counter(), Counter(), Counter()
    examples = []
    type_cause = defaultdict(Counter)
    for qid, gold in golds.items():
        q = questions.get(qid) or {}
        pred = preds.get(qid, {"type": "abstain"})
        s = score_one(pred, gold)
        if s == 1:
            continue
        d = dumps.get(qid, {})
        trace = {}
        if args.logs:
            p = os.path.join(args.logs, qid + ".json")
            if os.path.isfile(p):
                with open(p, encoding="utf-8") as fh:
                    trace = json.load(fh)
        intent = (d.get("feats") or {}).get("intent") or (trace.get("spec") or {}).get("intent") or "unknown"
        cause = reason(pred, d, trace)
        by_type[gold["type"]] += 1
        by_intent[intent] += 1
        by_cause[cause] += 1
        type_cause[gold["type"]][cause] += 1
        examples.append({
            "business_id": q.get("business_id"),
            "question": q.get("question"),
            "reference_type": gold.get("type"),
            "reference_answer": gold.get("answer"),
            "prediction": pred,
            "raw_candidate": d.get("pred"),
            "intent": intent, "cause": cause,
            "template_strength": (d.get("feats") or {}).get("tpl_strength"),
            "trace_evidence": trace.get("ua_evidence"),
            "template_error": trace.get("template_error"),
            "score": s,
        })
    counts = Counter("wrong" if score_one(preds.get(i), g) == -1 else "abstain"
                     for i, g in golds.items() if score_one(preds.get(i), g) != 1)
    result = {
        "note": "TRAIN-only diagnosis. Counts depend on the predictions generated by this exact run.",
        "n_questions": len(golds),
        "missing": dict(counts),
        "by_reference_type": dict(by_type),
        "by_intent": dict(by_intent),
        "by_cause": dict(by_cause),
        "type_cause": {k: dict(v) for k, v in type_cause.items()},
        "examples": examples[:max(0, args.show)]
    }
    print(f"TRAIN misses: wrong={counts['wrong']}, abstain={counts['abstain']}")
    for heading, counts_for_heading in (
        ("reference type", by_type), ("intent", by_intent), ("cause", by_cause)
    ):
        print(f"\nBy {heading}:")
        for k, v in counts_for_heading.most_common(30):
            print(f"  {str(k):30s} {v:4d}")
    if args.show:
        print("\nFirst representative misses (TRAIN only):")
        for row in result["examples"][:args.show]:
            print(f"  [{row['reference_type']}/{row['cause']}] {str(row['question'])[:130]}")
    if args.out:
        os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
        with open(args.out, "w", encoding="utf-8") as fh:
            json.dump(result, fh, ensure_ascii=False, indent=2)
        print(f"Saved {args.out}")


if __name__ == "__main__":
    main()
